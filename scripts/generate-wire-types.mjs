import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { randomUUID } from 'node:crypto';

const repoRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const outputPath = path.join(repoRoot, 'web/src/types/generated/contracts.ts');
const contracts = [
  ['WorkflowContract', 'schemas/workflow.schema.json'],
  ['ProjectDescriptorContract', 'schemas/portable-project-descriptor.schema.json'],
  ['ProjectRegistryContract', 'schemas/user-project-registry.schema.json'],
  ['UserPreferencesContract', 'schemas/user-preferences.schema.json'],
  ['CredentialReferenceContract', 'schemas/credential-ref.schema.json'],
  ['RunStateContract', 'schemas/run-state.schema.json'],
  ['LintResultContract', 'schemas/lint-result.schema.json']
];

const quote = (value) => JSON.stringify(value);

const resolveRef = (root, ref) => {
  if (!ref.startsWith('#/')) return null;
  return ref.slice(2).split('/').reduce((value, key) => value?.[key.replaceAll('~1', '/').replaceAll('~0', '~')], root);
};

const schemaType = (schema, root, seen = new Set()) => {
  if (schema === true) return 'unknown';
  if (!schema || schema === false) return 'never';
  if (schema.$ref) {
    const target = resolveRef(root, schema.$ref);
    if (!target || seen.has(target)) return 'unknown';
    return schemaType(target, root, new Set([...seen, target]));
  }
  if (Object.hasOwn(schema, 'const')) return quote(schema.const);
  if (schema.enum) return schema.enum.map(quote).join(' | ') || 'never';
  if (schema.oneOf || schema.anyOf) return (schema.oneOf || schema.anyOf).map((part) => schemaType(part, root, seen)).join(' | ');
  if (schema.allOf) return schema.allOf.map((part) => schemaType(part, root, seen)).join(' & ');
  if (Array.isArray(schema.type)) return schema.type.map((type) => schemaType({ ...schema, type }, root, seen)).join(' | ');
  switch (schema.type) {
    case 'null': return 'null';
    case 'string': return 'string';
    case 'integer':
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return `Array<${schemaType(schema.items || {}, root, seen)}>`;
    case 'object':
    default: {
      if (!schema.properties && schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        return `Record<string, ${schemaType(schema.additionalProperties, root, seen)}>`;
      }
      if (!schema.properties && schema.type !== 'object') return 'unknown';
      const required = new Set(schema.required || []);
      const fields = Object.entries(schema.properties || {}).map(([key, value]) =>
        `  ${quote(key)}${required.has(key) ? '' : '?'}: ${schemaType(value, root, seen)};`
      );
      if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        fields.push(`  [key: string]: ${schemaType(schema.additionalProperties, root, seen)};`);
      }
      return `{\n${fields.join('\n')}\n}`;
    }
  }
};

const body = contracts.map(([name, relativePath]) => {
  const schema = JSON.parse(fs.readFileSync(path.join(repoRoot, relativePath), 'utf8'));
  return `export type ${name} = ${schemaType(schema, schema)};`;
}).join('\n\n');

const generated = `// Generated by scripts/generate-wire-types.mjs. Do not edit.\n\n${body}\n`;
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== generated) {
    console.error('Generated wire types are stale. Run npm run generate:types.');
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  const temporary = path.join(path.dirname(outputPath), `.${path.basename(outputPath)}.tmp-${randomUUID()}`);
  const fd = fs.openSync(temporary, 'wx');
  try {
    fs.writeFileSync(fd, generated);
    fs.fsyncSync(fd);
  } finally {
    fs.closeSync(fd);
  }
  fs.renameSync(temporary, outputPath);
}
